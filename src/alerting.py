"""GitHub Issues alerting for Modern Dicompyler.

Alert triggers implemented:
- /health failing twice consecutively;
- a demo-case analysis failing;
- analysis failure rate exceeding 20% over a five-minute window.

Every alert creates a GitHub Issue labelled ``on-call`` (with a cooldown to
avoid issue storms). Issue bodies contain timestamps, environment, endpoint,
error class, trace id and metric values plus a diagnostic checklist - and
never PHI or secrets. When GITHUB_TOKEN/GITHUB_REPO are not configured the
alert is logged instead, so local development is unaffected.
"""
from __future__ import annotations

import threading
import time
from collections import deque
from datetime import UTC, datetime

import requests
from prometheus_client import REGISTRY

from src.config import (
    ALERT_COOLDOWN_SECONDS,
    DEPLOYMENT_URL,
    ENVIRONMENT,
    FAILURE_RATE_MIN_SAMPLES,
    FAILURE_RATE_THRESHOLD,
    FAILURE_RATE_WINDOW_SECONDS,
    GITHUB_API_BASE,
    GITHUB_REPO,
    GITHUB_TOKEN,
    HEALTH_FAILURE_ALERT_THRESHOLD,
    ONCALL_LABEL,
)
from src.telemetry import get_logger, trace_id_var

logger = get_logger("alerting")

DIAGNOSTIC_CHECKLIST = [
    "Check the API container/service is running (docker compose ps).",
    "Check GET /health and confirm the database field is true.",
    "Check GET /metrics for rtqa_analysis_failures_total by error_class.",
    "Inspect structured logs for the trace_id in this issue.",
    "Re-run the synthetic demo case to confirm baseline functionality.",
    "If deployment is unhealthy, roll back to the last known-good image/tag (see docs/deployment.md).",
]


def _sum_metric_samples(sample_prefix: str) -> float:
    """Sum all exposition samples whose name starts with the given prefix."""
    total = 0.0
    for metric in REGISTRY.collect():
        for sample in metric.samples:
            if sample.name.startswith(sample_prefix):
                total += sample.value
    return total


def _database_up_value() -> float:
    value = REGISTRY.get_sample_value("rtqa_database_up")
    return float(value) if value is not None else 0.0


class AlertManager:
    """Cooldown-guarded GitHub Issue alerting plus a rolling failure window."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._last_fired: dict[str, float] = {}
        self._samples: deque[tuple[float, bool]] = deque()
        self._consecutive_health_failures = 0

    # -- cooldown ---------------------------------------------------------
    def _cooldown_ok(self, alert_key: str) -> bool:
        now = time.monotonic()
        with self._lock:
            last = self._last_fired.get(alert_key)
            if last is not None and (now - last) < ALERT_COOLDOWN_SECONDS:
                return False
            self._last_fired[alert_key] = now
            return True

    # -- issue creation ----------------------------------------------------
    def fire_issue(
        self,
        alert_key: str,
        *,
        title: str,
        endpoint: str,
        error_class: str,
        extra_lines: list[str] | None = None,
    ) -> None:
        if not self._cooldown_ok(alert_key):
            return
        if not (GITHUB_TOKEN and GITHUB_REPO):
            logger.warning(
                "alert_github_disabled",
                extra={
                    "event": "alert",
                    "alert_key": alert_key,
                    "error_class": error_class,
                    "title": title,
                },
            )
            return

        checklist = "\n".join(f"- [ ] {item}" for item in DIAGNOSTIC_CHECKLIST)
        extras = "\n".join(f"- {line}" for line in (extra_lines or []))
        body = "\n".join(
            [
                "## Automated on-call alert",
                "",
                f"- **Timestamp (UTC):** {datetime.now(UTC).isoformat()}",
                f"- **Environment:** {ENVIRONMENT}",
                f"- **Affected endpoint:** {endpoint}",
                f"- **Error class:** {error_class}",
                f"- **Trace ID:** `{trace_id_var.get() or 'n/a'}`",
                f"- **Deployment URL:** {DEPLOYMENT_URL or 'not configured'}",
                "",
                "### Metric snapshot",
                f"- rtqa_analysis_requests_total (sum): {_sum_metric_samples('rtqa_analysis_requests_total'):.0f}",
                f"- rtqa_analysis_failures_total (sum): {_sum_metric_samples('rtqa_analysis_failures_total'):.0f}",
                f"- rtqa_database_up: {_database_up_value():.0f}",
                "",
                *( ["### Details", "", extras, ""] if extras else [] ),
                "### Diagnostic checklist",
                "",
                checklist,
                "",
                "_No PHI or secrets are included in this issue. "
                "Generated by the Modern Dicompyler alerting module._",
            ]
        )
        url = f"{GITHUB_API_BASE}/repos/{GITHUB_REPO}/issues"
        try:
            response = requests.post(
                url,
                json={"title": f"[on-call] {title}", "body": body, "labels": [ONCALL_LABEL]},
                headers={
                    "Authorization": f"Bearer {GITHUB_TOKEN}",
                    "Accept": "application/vnd.github+json",
                },
                timeout=10,
            )
            if response.status_code >= 300:
                logger.warning(
                    "alert_issue_create_failed",
                    extra={"status_code": response.status_code, "alert_key": alert_key},
                )
            else:
                logger.warning(
                    "alert_issue_created",
                    extra={"alert_key": alert_key, "error_class": error_class},
                )
        except requests.RequestException as exc:
            logger.warning(
                "alert_issue_request_failed",
                extra={"error_class": type(exc).__name__, "alert_key": alert_key},
            )

    # -- trigger 1: consecutive health failures ----------------------------
    def record_health(self, ok: bool) -> None:
        if ok:
            with self._lock:
                self._consecutive_health_failures = 0
            return
        with self._lock:
            self._consecutive_health_failures += 1
            failures = self._consecutive_health_failures
        if failures >= HEALTH_FAILURE_ALERT_THRESHOLD:
            self.fire_issue(
                "health-consecutive-failures",
                title="Health endpoint failing consecutively",
                endpoint="/health",
                error_class="HealthCheckFailed",
                extra_lines=[f"Consecutive /health failures: {failures}"],
            )

    # -- trigger 2: demo-case failure ---------------------------------------
    def alert_demo_case_failure(self, error_class: str) -> None:
        self.fire_issue(
            "demo-case-failure",
            title="Synthetic demo-case analysis failed",
            endpoint="/api/v1/demo-case",
            error_class=error_class,
        )

    # -- trigger 3: failure rate over five minutes ---------------------------
    def record_analysis_outcome(self, route: str, ok: bool) -> None:
        now = time.time()
        with self._lock:
            self._samples.append((now, ok))
            cutoff = now - FAILURE_RATE_WINDOW_SECONDS
            while self._samples and self._samples[0][0] < cutoff:
                self._samples.popleft()
            sample_count = len(self._samples)
            failure_count = sum(1 for _, success in self._samples if not success)
        rate = failure_count / sample_count if sample_count else 0.0
        if (
            sample_count >= FAILURE_RATE_MIN_SAMPLES
            and rate > FAILURE_RATE_THRESHOLD
            and self._cooldown_ok("analysis-failure-rate")
        ):
            self.fire_issue(
                "analysis-failure-rate",
                title="Analysis failure rate above 20% over five minutes",
                endpoint=route,
                error_class="ElevatedFailureRate",
                extra_lines=[
                    f"Failures in window: {failure_count} of {sample_count} "
                    f"({rate:.1%}); threshold {FAILURE_RATE_THRESHOLD:.0%} "
                    f"over {FAILURE_RATE_WINDOW_SECONDS} seconds."
                ],
            )


_manager = AlertManager()


def record_health(ok: bool) -> None:
    _manager.record_health(ok)


def alert_demo_case_failure(error_class: str) -> None:
    _manager.alert_demo_case_failure(error_class)


def record_analysis_outcome(route: str, ok: bool) -> None:
    _manager.record_analysis_outcome(route, ok)
